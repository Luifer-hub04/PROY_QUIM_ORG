"""### 2. Dispersión de los pares más fuertes (cada punto = una medición, el color resalta el signo de ρ)"""

import plotly.express as px
import pandas as pd
import numpy as np
from plotly.subplots import make_subplots
import plotly.graph_objects as go

# Determinar cuántos gráficos mostrar (máximo 6)
N = min(6, len(top))
filas = int(np.ceil(N / 2))

# Crear una cuadrícula de subgráficos utilizando make_subplots para tener control absoluto de cada eje
fig = make_subplots(
    rows=filas,
    cols=2,
    subplot_titles=[f"{r.x} vs {r.y} (ρ = {r.rho:.2f})" for r in top.head(N).itertuples()],
    horizontal_spacing=0.15,
    vertical_spacing=0.15
)

# Color según el signo de la correlación
color_map = {"Positiva": "#9C6A33", "Negativa": "#3E6E7E"}

for idx, r in enumerate(top.head(N).itertuples()):
    row = (idx // 2) + 1
    col = (idx % 2) + 1

    # Filtrar y preparar datos
    d_sub = params_clean[[r.x, r.y]].dropna()
    signo = "Positiva" if r.rho > 0 else "Negativa"
    color_puntos = color_map[signo]

    # Añadir trazo de dispersión (Scatter)
    fig.add_trace(
        go.Scatter(
            x=d_sub[r.x],
            y=d_sub[r.y],
            mode="markers",
            name=f"{signo} (ρ={r.rho:.2f})",
            marker=dict(color=color_puntos, size=8, opacity=0.75, line=dict(width=0.6, color="white")),
            showlegend=False
        ),
        row=row, col=col
    )

    # Calcular y añadir línea de tendencia OLS
    if len(d_sub) > 2:
        m, b = np.polyfit(d_sub[r.x], d_sub[r.y], 1)
        x_line = np.linspace(d_sub[r.x].min(), d_sub[r.x].max(), 100)
        y_line = m * x_line + b
        fig.add_trace(
            go.Scatter(
                x=x_line,
                y=y_line,
                mode="lines",
                line=dict(color="#8C857B", width=1.5, dash="dash"),
                showlegend=False
            ),
            row=row, col=col
        )

    # Configurar de manera explícita los títulos de los ejes correspondientes para este subgráfico
    fig.update_xaxes(title_text=r.x, row=row, col=col)
    fig.update_yaxes(title_text=r.y, row=row, col=col)

# Personalizar diseño general
fig.update_layout(
    title_text="Relación entre las propiedades más correlacionadas (Interactivo)",
    title_font=dict(size=16, family="Arial", color="#2B2622"),
    template="plotly_white",
    width=1000,
    height=350 * filas
)

fig.show()

