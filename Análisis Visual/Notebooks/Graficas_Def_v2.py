def barras_agrupadas(tabla, titulo, xlabel, leyenda, colores, ax=None, figsize=(11, 5.5)):
    """tabla: crosstab (filas = eje X, columnas = barras dentro de cada grupo)"""
    creado = ax is None
    if creado:
        fig, ax = plt.subplots(figsize=figsize)
    n = tabla.shape[1]
    ancho = 0.8 / n
    x = np.arange(tabla.shape[0])
    for j, col in enumerate(tabla.columns):
        pos = x - 0.4 + ancho * (j + 0.5)
        barras = ax.bar(pos, tabla[col].values, width=ancho * 0.92, color=colores[j], label=col, zorder=3)
        for b, v in zip(barras, tabla[col].values):
            if v > 0:
                ax.text(b.get_x() + b.get_width() / 2, v + tabla.values.max() * 0.01, int(v),
                        ha="center", va="bottom", fontsize=8, color=TEXTO)
    ax.set_xticks(x); ax.set_xticklabels(tabla.index, rotation=0)
    ax.yaxis.set_major_locator(MaxNLocator(integer=True))   # frecuencias enteras
    ax.set_ylim(0, tabla.values.max() * 1.12)
    ax.set_xlabel(xlabel); ax.set_ylabel("Frecuencia (n.º de registros)")
    ax.set_title(titulo)
    ax.grid(axis="x", visible=False)
    ax.legend(title=leyenda, frameon=False, bbox_to_anchor=(1.01, 1), loc="upper left")
    if creado:
        plt.tight_layout(); plt.show()

