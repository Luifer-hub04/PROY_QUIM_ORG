# Creamos una copia para limpiar los datos sin alterar el original de forma destructiva
params_clean = params.copy()

for col in params_clean.columns:
    # Convertimos a string para aplicar operaciones de texto
    params_clean[col] = params_clean[col].astype(str)
    # Reemplazamos comas decimales por puntos
    params_clean[col] = params_clean[col].str.replace(',', '.', regex=False)
    # Extraemos el primer número decimal o entero que aparezca en el texto
    params_clean[col] = params_clean[col].str.extract(r'([-+]?\d*\.?\d+)')
    # Convertimos a tipo de dato float numérico
    params_clean[col] = pd.to_numeric(params_clean[col], errors='coerce')

# Calculamos la correlación de Spearman sobre los datos limpios
corr = params_clean.corr(method="spearman")

